"""
Guardrails for OPS-1 — the RuleSet policy builder (CR-15 amend, CR-12, CR-20).

Enforces:
  • RuleSet mutations are ADMIN-only (REVIEWER is read-only) and go through the authenticated DAL
    (requireSession → auth() → DB) at the server-action boundary;
  • mutations are organizationId-scoped and run inside runWithOrg (RLS, M1-02);
  • the builder configures ONLY the client-policy fields the engine consumes — it never authors a
    free-text recommendation (the recommendation stays generated + evidence-only); author inputs are
    verdict-guarded (CR-12);
  • the policy UI copy carries no verdict language.

Run: pytest tests/guardrails -q
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ADMIN = ROOT / "apps/web/lib/rules/ruleset-admin.ts"
ACTIONS = ROOT / "apps/web/app/(cockpit)/policies/actions.ts"
PAGE = ROOT / "apps/web/app/(cockpit)/policies/page.tsx"
BUILDER = ROOT / "apps/web/app/(cockpit)/policies/PolicyBuilder.tsx"

VERDICT = re.compile(r"\b(violation|breach|back[- ]?charge|penalty|liable|guilty|enforce)\b", re.I)
ALLOW_MARK = "guardrail:allow-verdict-term"


def test_builder_files_present():
    for f in (ADMIN, ACTIONS, PAGE, BUILDER):
        assert f.exists(), f"missing {f.name}"


def test_mutations_are_admin_gated():
    src = ACTIONS.read_text()
    assert 'role !== "ADMIN"' in src, "RuleSet mutations must be ADMIN-only (REVIEWER read-only)"
    # every mutation goes through the admin+session gate before any write
    assert src.count("requireAdminOrg") >= 3, "create/update/delete must each pass through the ADMIN gate"
    for act in ("createPolicyAction", "updatePolicyAction", "deletePolicyAction"):
        assert act in src, f"missing action {act}"


def test_mutations_go_through_the_authenticated_dal():
    src = ACTIONS.read_text()
    assert src.lstrip().startswith('"use server"'), "policy actions must be server actions"
    assert "requireSession" in src, "mutations must validate the session at the DAL (CR-20)"
    assert "runWithOrg" in src, "mutations must run inside runWithOrg (RLS, M1-02)"


def test_mutations_are_org_scoped():
    src = ADMIN.read_text()
    # every CRUD helper is keyed on organizationId (multi-tenant native)
    assert src.count("organizationId") >= 6, "RuleSet admin queries must be organizationId-scoped"
    for fn in ("listRuleSets", "createRuleSet", "updateRuleSet", "deleteRuleSet"):
        assert f"export async function {fn}(organizationId: string" in src, f"{fn} must take organizationId"


def test_builder_never_authors_a_recommendation_and_verdict_guards_inputs():
    src = ADMIN.read_text()
    # the recommendation is generated by the engine — the builder must not write a recommendation field
    assert "recommendation:" not in src, "the builder must NOT author a recommendation (it stays generated + evidence-only)"
    # author free-text is verdict-guarded (CR-12)
    assert "validateRuleSetInput" in src and "VERDICT" in src, "policy inputs must be verdict-guarded"
    # and it must not touch the model-owned anomaly type
    assert "classification:" not in src, "the RuleSet builder must never set the anomaly classification (model owns it, CR-19)"


def test_policy_ui_copy_is_evidence_framed():
    offenders = []
    for f in (PAGE, BUILDER):
        for i, line in enumerate(f.read_text(errors="ignore").splitlines(), 1):
            if ALLOW_MARK in line:
                continue
            if VERDICT.search(line):
                offenders.append(f"{f.name}:{i}: {line.strip()}")
    assert not offenders, "verdict language in policy UI copy (CR-12):\n" + "\n".join(offenders)
